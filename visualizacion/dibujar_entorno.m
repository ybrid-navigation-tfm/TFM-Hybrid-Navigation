function [graficos,escenario,dinamicos] = validar_entradas( ...
    graficos,escenario,dinamicos)
%VALIDAR_ENTRADAS Comprueba la coherencia del modulo.

%% Estructura grafica
if ~isstruct(graficos) || ~isscalar(graficos) || ...
        ~isfield(graficos,'activa')
    error('dibujar_entorno:GraficosNoValidos', ...
        ['graficos debe ser la estructura obtenida mediante ' ...
         'inicializar_figura.m.']);
end

graficos.activa = validar_logico( ...
    graficos.activa,'graficos.activa');

if ~graficos.activa
    return;
end

camposGraficos = { ...
    'inicializada', ...
    'figura', ...
    'ejes', ...
    'capas', ...
    'objetos', ...
    'estilo'};

for i = 1:numel(camposGraficos)
    if ~isfield(graficos,camposGraficos{i})
        error('dibujar_entorno:GraficosIncompletos', ...
            'Falta graficos.%s.',camposGraficos{i});
    end
end

if ~graficos.inicializada || ...
        ~isgraphics(graficos.figura,'figure') || ...
        ~isgraphics(graficos.ejes,'axes')
    error('dibujar_entorno:FiguraNoInicializada', ...
        ['La figura no esta inicializada o ha sido cerrada. ' ...
         'Ejecute de nuevo inicializar_figura.m.']);
end

if ~isstruct(graficos.capas) || ...
        ~isfield(graficos.capas,'entorno') || ...
        ~isfield(graficos.capas,'obstaculosDinamicos') || ...
        ~isgraphics(graficos.capas.entorno) || ...
        ~isgraphics(graficos.capas.obstaculosDinamicos)
    error('dibujar_entorno:CapasNoValidas', ...
        'Las capas graficas del entorno no son validas.');
end

if ~isstruct(graficos.objetos) || ...
        ~isstruct(graficos.estilo)
    error('dibujar_entorno:EstructuraInternaNoValida', ...
        'graficos.objetos y graficos.estilo deben ser estructuras.');
end

camposEstilo = { ...
    'colorBordeMapa', ...
    'colorObstaculoEstatico', ...
    'colorTextoEstatico', ...
    'colorObstaculoDinamico', ...
    'colorFlechaDinamica', ...
    'colorTextoDinamico', ...
    'colorInicio', ...
    'colorMeta', ...
    'anchoBordeMapa', ...
    'anchoFlecha', ...
    'alphaObstaculoDinamico', ...
    'tamanoInicio', ...
    'tamanoMeta', ...
    'tamanoFuenteObjetos', ...
    'anguloCirculo'};

for i = 1:numel(camposEstilo)
    if ~isfield(graficos.estilo,camposEstilo{i})
        error('dibujar_entorno:EstiloIncompleto', ...
            'Falta graficos.estilo.%s.',camposEstilo{i});
    end
end

%% Escenario
if ~isstruct(escenario) || ~isscalar(escenario)
    error('dibujar_entorno:EscenarioNoValido', ...
        'escenario debe proceder de escenarios.m.');
end

camposEscenario = { ...
    'limites', ...
    'inicio', ...
    'meta', ...
    'obstaculosEstaticos'};

for i = 1:numel(camposEscenario)
    if ~isfield(escenario,camposEscenario{i})
        error('dibujar_entorno:EscenarioIncompleto', ...
            'Falta escenario.%s.',camposEscenario{i});
    end
end

if ~isnumeric(escenario.limites) || ...
        ~isreal(escenario.limites) || ...
        numel(escenario.limites) ~= 4 || ...
        any(~isfinite(escenario.limites(:)))
    error('dibujar_entorno:LimitesNoValidos', ...
        'escenario.limites debe ser [xmin xmax ymin ymax].');
end

escenario.limites = reshape( ...
    double(escenario.limites),1,4);

if escenario.limites(1) >= escenario.limites(2) || ...
        escenario.limites(3) >= escenario.limites(4)
    error('dibujar_entorno:OrdenLimitesNoValido', ...
        'Debe cumplirse xmin < xmax e ymin < ymax.');
end

if ~isnumeric(escenario.inicio) || ...
        ~isreal(escenario.inicio) || ...
        numel(escenario.inicio) < 2 || ...
        any(~isfinite(escenario.inicio(:)))
    error('dibujar_entorno:InicioNoValido', ...
        'escenario.inicio debe contener al menos [x y].');
end

escenario.inicio = ...
    reshape(double(escenario.inicio),1,[]);

if ~isnumeric(escenario.meta) || ...
        ~isreal(escenario.meta) || ...
        numel(escenario.meta) ~= 2 || ...
        any(~isfinite(escenario.meta(:)))
    error('dibujar_entorno:MetaNoValida', ...
        'escenario.meta debe tener formato [x y].');
end

escenario.meta = reshape( ...
    double(escenario.meta),1,2);

estaticos = escenario.obstaculosEstaticos;

if isempty(estaticos)
    escenario.obstaculosEstaticos = zeros(0,4);
elseif ~isnumeric(estaticos) || ...
        ~isreal(estaticos) || ...
        size(estaticos,2) ~= 4 || ...
        any(~isfinite(estaticos(:))) || ...
        any(estaticos(:,3:4) <= 0,'all')
    error('dibujar_entorno:EstaticosNoValidos', ...
        ['escenario.obstaculosEstaticos debe ser una matriz N x 4 ' ...
         'con formato [x y ancho alto].']);
else
    escenario.obstaculosEstaticos = double(estaticos);
end

%% Obstaculos dinamicos
if isempty(dinamicos)
    dinamicos = struct( ...
        'id',{},'pos',{},'vel',{},'radio',{});
elseif ~isstruct(dinamicos)
    error('dibujar_entorno:DinamicosNoValidos', ...
        'obstaculosDinamicos debe ser un vector de estructuras.');
else
    for i = 1:numel(dinamicos)
        camposDinamico = {'pos','vel','radio'};

        for j = 1:numel(camposDinamico)
            if ~isfield(dinamicos(i),camposDinamico{j})
                error('dibujar_entorno:CampoDinamicoAusente', ...
                    ['Falta el campo "%s" en el obstaculo ' ...
                     'dinamico %d.'],camposDinamico{j},i);
            end
        end

        if ~isnumeric(dinamicos(i).pos) || ...
                ~isreal(dinamicos(i).pos) || ...
                numel(dinamicos(i).pos) ~= 2 || ...
                any(~isfinite(dinamicos(i).pos(:)))
            error('dibujar_entorno:PosicionDinamicaNoValida', ...
                'La posicion de D%d debe tener formato [x y].',i);
        end

        if ~isnumeric(dinamicos(i).vel) || ...
                ~isreal(dinamicos(i).vel) || ...
                numel(dinamicos(i).vel) ~= 2 || ...
                any(~isfinite(dinamicos(i).vel(:)))
            error('dibujar_entorno:VelocidadDinamicaNoValida', ...
                'La velocidad de D%d debe tener formato [vx vy].',i);
        end

        if ~isnumeric(dinamicos(i).radio) || ...
                ~isscalar(dinamicos(i).radio) || ...
                ~isreal(dinamicos(i).radio) || ...
                ~isfinite(dinamicos(i).radio) || ...
                dinamicos(i).radio <= 0
            error('dibujar_entorno:RadioDinamicoNoValido', ...
                'El radio de D%d debe ser positivo.',i);
        end

        dinamicos(i).pos = reshape( ...
            double(dinamicos(i).pos),1,2);

        dinamicos(i).vel = reshape( ...
            double(dinamicos(i).vel),1,2);

        dinamicos(i).radio = ...
            double(dinamicos(i).radio);
    end
end
end

function valor = validar_logico(valor,nombre)
%VALIDAR_LOGICO Convierte un escalar logico o binario.

if islogical(valor) && isscalar(valor)
    return;
end

if isnumeric(valor) && isscalar(valor) && ...
        isreal(valor) && isfinite(valor) && ...
        (valor == 0 || valor == 1)
    valor = logical(valor);
    return;
end

error('dibujar_entorno:IndicadorNoValido', ...
    '%s debe ser un escalar logico o binario.',nombre);
end
